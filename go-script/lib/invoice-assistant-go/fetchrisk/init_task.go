package fetchrisk

import (
	"fmt"
	"strings"

	"invoice-assistant-skill/go-script/lib/invoice-assistant-go/common"
)

func InitTask(inputPath string) (string, error) {
	return InitTaskWithClient(inputPath, nil)
}

/**
 * InitTaskWithClient 创建显式绑定企业快照的取票任务。
 *
 * @param inputPath Agent 生成的新任务输入 JSON 路径。
 * @param client 可选的 Gateway APIClient。
 * @returns 新任务状态文件的绝对路径。
 */
func InitTaskWithClient(inputPath string, client *common.APIClient) (string, error) {
	var runErr error
	defer func() {
		if runErr != nil {
			common.AppendMessageLog("任务参数初始化失败: " + runErr.Error())
		}
	}()

	common.AppendMessageLog("初始化发票获取及风险分析任务参数")
	common.AppendMessageLog("ai提供参数文件路径: " + inputPath)
	payload, err := common.ReadJSONFile(inputPath)
	if err != nil {
		runErr = err
		return "", runErr
	}
	workspaceDir, params, steps, err := normalizePayload(payload)
	if err != nil {
		runErr = err
		return "", runErr
	}
	config := common.LoadWorkspaceConfig()
	enterpriseContext, err := common.ResolveBoundEnterprise(client, common.StringValue(config[common.APIKey]), common.StringValue(params["uscc"]))
	if err != nil {
		runErr = err
		return "", runErr
	}
	params = common.ApplyEnterpriseContext(params, enterpriseContext)
	state, err := CreateTaskState(workspaceDir, params, steps, enterpriseContext)
	if err != nil {
		runErr = err
		return "", runErr
	}
	if err := state.Save(); err != nil {
		runErr = err
		return "", runErr
	}
	common.AppendMessageLog("初始化成功，本次任务相关数据将保存至 " + state.Path)
	return state.Path, nil
}

func normalizePayload(payload map[string]any) (string, map[string]any, []map[string]any, error) {
	if _, supplied := payload[common.EnterpriseContextKey]; supplied {
		return "", nil, nil, fmt.Errorf("enterprise_context is generated by the script and must not be supplied")
	}
	workspaceDir := common.NormalizeWorkspaceDir(common.StringValue(payload["workspace_dir"]))
	params, ok := payload["params"].(map[string]any)
	if !ok || len(params) == 0 {
		return "", nil, nil, fmt.Errorf("missing required non-empty params object")
	}
	if strings.TrimSpace(common.StringValue(params["uscc"])) == "" {
		return "", nil, nil, fmt.Errorf("missing required param: params.uscc")
	}
	if _, supplied := params[common.EnterpriseContextKey]; supplied {
		return "", nil, nil, fmt.Errorf("params.enterprise_context is generated by the script and must not be supplied")
	}
	steps := normalizeSteps(payload)
	if len(steps) == 0 {
		return "", nil, nil, fmt.Errorf("cannot generate execution steps")
	}
	return workspaceDir, params, steps, nil
}

func normalizeSteps(payload map[string]any) []map[string]any {
	if rawSteps, ok := payload["steps"].([]any); ok && len(rawSteps) > 0 {
		out := []map[string]any{}
		for idx, item := range rawSteps {
			switch value := item.(type) {
			case string:
				if strings.TrimSpace(value) != "" {
					out = append(out, map[string]any{"name": strings.TrimSpace(value), "index": idx + 1})
				}
			case map[string]any:
				name := strings.TrimSpace(common.StringValue(value["name"]))
				if name == "" {
					continue
				}
				step := map[string]any{"name": name, "index": idx + 1, "enabled": true}
				if index, ok := value["index"].(float64); ok && index > 0 {
					step["index"] = int(index)
				}
				if enabled, ok := value["enabled"].(bool); ok {
					step["enabled"] = enabled
				}
				out = append(out, step)
			}
		}
		if len(out) > 0 {
			return out
		}
	}
	params, _ := payload["params"].(map[string]any)
	outputRequirement := strings.TrimSpace(common.StringValue(params["outputRequirement"]))
	if outputRequirement == "" {
		outputRequirement = "只获取"
	}
	withAttachment, _ := params["needAttachments"].(bool)
	names := []string{"fetch_invoices", "summarize"}
	if withAttachment {
		names = append(names, "fetch_attachments")
	}
	names = append(names, "fetch_deduction", "generate_invoice_list")
	if outputRequirement == "获取+统计" || outputRequirement == "获取+分析" {
		names = append(names, "analyze")
	}
	if outputRequirement == "获取+分析" {
		names = append(names, "build_invoice_context_data", "risk_analysis")
	}
	out := make([]map[string]any, 0, len(names))
	for i, name := range names {
		out = append(out, map[string]any{"name": name, "index": i + 1})
	}
	return out
}
