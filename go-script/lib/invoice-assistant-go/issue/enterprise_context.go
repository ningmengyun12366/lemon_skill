package issue

import (
	"fmt"
	"os"
	"strings"

	"invoice-assistant-skill/go-script/lib/invoice-assistant-go/common"
)

/**
 * prepareIssueTaskInput 从服务端解析销售方企业并生成不可变的新任务输入。
 *
 * @param raw Agent 提供的原始开票输入。
 * @param taskFile 可选的既有任务路径；存在时只允许复用其中的企业快照。
 * @param client 可选的 Gateway APIClient。
 * @returns 标准化输入、企业快照和错误。
 */
func prepareIssueTaskInput(raw map[string]any, taskFile string, client *common.APIClient) (map[string]any, map[string]any, error) {
	if _, supplied := raw[common.EnterpriseContextKey]; supplied {
		return nil, nil, fmt.Errorf("enterprise_context is generated by the script and must not be supplied")
	}
	uscc := strings.TrimSpace(common.StringValue(raw["uscc"]))
	if uscc == "" {
		return nil, nil, fmt.Errorf("missing required param: uscc")
	}
	if strings.TrimSpace(taskFile) != "" {
		if _, err := os.Stat(taskFile); err == nil {
			task, readErr := common.ReadJSONFile(taskFile)
			if readErr != nil {
				return nil, nil, readErr
			}
			enterpriseContext, contextErr := common.EnterpriseContextFromTask(task)
			if contextErr != nil {
				return nil, nil, contextErr
			}
			contextUSCC := strings.TrimSpace(common.StringValue(enterpriseContext["uscc"]))
			if uscc != contextUSCC {
				return nil, nil, fmt.Errorf("raw input uscc=%s does not match enterprise_context uscc=%s", uscc, contextUSCC)
			}
			normalized, normalizeErr := NormalizeRawInput(common.ApplyEnterpriseContext(raw, enterpriseContext))
			return normalized, enterpriseContext, normalizeErr
		} else if !os.IsNotExist(err) {
			return nil, nil, err
		}
	}
	config := common.LoadWorkspaceConfig()
	enterpriseContext, err := common.ResolveBoundEnterprise(client, common.StringValue(config[common.APIKey]), uscc)
	if err != nil {
		return nil, nil, err
	}
	normalized, err := NormalizeRawInput(common.ApplyEnterpriseContext(raw, enterpriseContext))
	if err != nil {
		return nil, nil, err
	}
	return normalized, enterpriseContext, nil
}
